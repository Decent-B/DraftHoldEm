// Vercel build step: writes public/config.js so the deployed client knows which game
// server to dial. It fails the build instead of shipping a client that cannot connect,
// because that failure would otherwise only show up in a player's browser console.
import { readFile, writeFile } from "node:fs/promises";
import { argv } from "node:process";
import { pathToFileURL } from "node:url";

const clientConfigPath = new URL("../public/config.js", import.meta.url);
const vercelConfigPath = new URL("../vercel.json", import.meta.url);

// Accepts wss:// or https:// and always emits wss://: an HTTPS page cannot open an
// insecure socket, and the browser blocks the mixed-content attempt silently.
export function clientConfigSource(gameServerUrl) {
  let url;
  try {
    url = new URL(gameServerUrl);
  } catch {
    throw new Error(`GAME_SERVER_URL is not a URL: ${gameServerUrl}`);
  }
  if (!["https:", "wss:"].includes(url.protocol)) {
    throw new Error(`GAME_SERVER_URL must start with wss:// or https://, got ${gameServerUrl}`);
  }
  return [
    "// Generated by scripts/build-client-config.mjs during the Vercel build.",
    `window.DRAFT_HOLDEM_CONFIG = { gameServerUrl: ${JSON.stringify(`wss://${url.host}`)} };`,
    "",
  ].join("\n");
}

// The Content-Security-Policy is static in vercel.json while the endpoint comes from an
// environment variable, so the two can drift apart. A mismatch blocks every socket in the
// browser with nothing wrong on the server, which is a miserable thing to debug.
export function assertCspAllowsGameServer(vercelConfig, gameServerUrl) {
  const socketOrigin = `wss://${new URL(gameServerUrl).host}`;
  const policies = (vercelConfig.headers ?? [])
    .flatMap((rule) => rule.headers ?? [])
    .filter((header) => header.key.toLowerCase() === "content-security-policy")
    .map((header) => header.value);
  if (policies.length === 0) throw new Error("vercel.json declares no Content-Security-Policy");
  for (const policy of policies) {
    const connectSrc = policy.split(";").map((directive) => directive.trim())
      .find((directive) => directive.startsWith("connect-src"));
    if (!connectSrc?.split(/\s+/).includes(socketOrigin)) {
      throw new Error(`vercel.json connect-src must list ${socketOrigin}, or the browser will block the socket`);
    }
  }
}

async function build() {
  const gameServerUrl = process.env.GAME_SERVER_URL;
  if (!gameServerUrl) {
    throw new Error("GAME_SERVER_URL is not set; add it to the Vercel project's environment variables");
  }
  assertCspAllowsGameServer(JSON.parse(await readFile(vercelConfigPath, "utf8")), gameServerUrl);
  await writeFile(clientConfigPath, clientConfigSource(gameServerUrl));
  console.log(`Client configured for ${gameServerUrl}`);
}

// Runs as the Vercel build command; the helpers above are imported by its test.
if (argv[1] && import.meta.url === pathToFileURL(argv[1]).href) {
  try {
    await build();
  } catch (error) {
    // A one-line reason reads far better than a stack trace in a Vercel build log.
    console.error(`\nBuild failed: ${error.message}\n`);
    process.exitCode = 1;
  }
}
